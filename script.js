let imgScale = 1;
let imgX = 0, imgY = 0;
let isDragging = false;
let dragStartX = 0, dragStartY = 0;

function updateImgTransform() {
    document.getElementById('modal-img').style.transform =
        `translate(${imgX}px, ${imgY}px) scale(${imgScale})`;
}

// 滚轮缩放：限制在 0.2 ~ 5 倍之间
document.querySelector('.modal-left').addEventListener('wheel', function(e) {
    e.preventDefault();    // 阻止页面跟着滚动
    const step = e.deltaY > 0 ? -0.1 : 0.1;
    imgScale = Math.min(Math.max(0.2, imgScale + step), 5);
    updateImgTransform();
}, { passive: false });    // 不加这个，preventDefault 会被浏览器无视

// 按下：记录"鼠标和图片位置的差值"
document.querySelector('.modal-left').addEventListener('mousedown', function(e) {
    isDragging = true;
    dragStartX = e.clientX - imgX;
    dragStartY = e.clientY - imgY;
});

// 移动：图片跟着鼠标走（挂在 window 上，鼠标移出图片也能继续拖）
window.addEventListener('mousemove', function(e) {
    if (!isDragging) return;
    imgX = e.clientX - dragStartX;
    imgY = e.clientY - dragStartY;
    updateImgTransform();
});

// 松开：结束拖拽
window.addEventListener('mouseup', function() {
    isDragging = false;
});


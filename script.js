// ===== 10. PDF 阅读器 =====
const PDF_URL = 'paper.pdf';   // 你的 PDF 文件名
let pdfDoc = null;

async function loadPDF() {
    if (pdfDoc) return;   // 加载过一次就不再重复加载

    const loadingEl = document.getElementById('pdf-loading');
    try {
        // 加载 PDF（慢操作，用 await 等它完成，期间页面不卡）
        pdfDoc = await pdfjsLib.getDocument(PDF_URL).promise;
        loadingEl.style.display = 'none';

        // 先为每一页创建空盒子占位（此时什么都没画！）
        const container = document.getElementById('pdf-container');
        for (let i = 1; i <= pdfDoc.numPages; i++) {
            const pageDiv = document.createElement('div');
            pageDiv.className = 'pdf-page';
            pageDiv.dataset.page = i;
            container.appendChild(pageDiv);
        }

        // 使用 IntersectionObserver 盯梢每个占位盒子，滚动到可视区域时才画
        const observer = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    renderPDFPage(+entry.target.dataset.page, entry.target);
                    observer.unobserve(entry.target);   // 画过就不再盯梢
                }
            });
        }, { rootMargin: '200px' });   // 提前 200px 触发，滚动更顺滑

        document.querySelectorAll('.pdf-page').forEach(p => observer.observe(p));

    } catch (err) {
        loadingEl.innerHTML = '<p>PDF 加载失败：' + err.message + '</p>';
    }
}

// 把第 num 页画到 canvas 上
async function renderPDFPage(num, container) {
    const page = await pdfDoc.getPage(num);

    const dpr = window.devicePixelRatio || 1;              // 高分屏适配
    const viewport = page.getViewport({ scale: 1.5 * dpr });

    const canvas = document.createElement('canvas');
    canvas.width = viewport.width;
    canvas.height = viewport.height;
    canvas.style.width = (viewport.width / dpr) + 'px';    // CSS 尺寸恢复正常
    canvas.style.height = (viewport.height / dpr) + 'px';

    container.appendChild(canvas);

    await page.render({
        canvasContext: canvas.getContext('2d'),
        viewport: viewport
    }).promise;
}